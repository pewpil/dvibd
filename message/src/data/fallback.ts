export interface User {
  id: string;
  name: string;
  handle: string;
  avatar: string;
  status: "online" | "offline" | "idle";
  bio: string;
  role: string;
  email: string;
}

export interface Conversation {
  id: string;
  type: "direct" | "channel";
  title: string;
  avatar: string;
  subtitle: string;
  communityName: string;
  lastMessage: string;
  lastSenderName: string;
  timestamp: string;
  unreadCount: number;
  presenceStatus: "online" | "offline" | "idle";
  memberCount: number;
  isMuted: boolean;
}

export interface Message {
  id: string;
  senderId: string;
  senderName: string;
  senderAvatar: string;
  content: string;
  timestamp: string;
  isOutgoing: boolean;
  status: "sent" | "delivered" | "read";
  mediaUrl?: string;
  mediaName?: string;
  mediaSize?: string;
}

export interface SharedFile {
  id: string;
  name: string;
  size: string;
  extension: string;
  timestamp: string;
}

export interface SharedLink {
  id: string;
  title: string;
  url: string;
  domain: string;
}

export interface Participant {
  id: string;
  name: string;
  handle: string;
  avatar: string;
  role: string;
  bio: string;
  status: "online" | "offline" | "idle";
}

